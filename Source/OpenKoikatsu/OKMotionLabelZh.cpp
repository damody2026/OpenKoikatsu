	const auto Reference = [](const FString& Source)
	{
		FString Out;
		for (int32 At=0; At<Source.Len();)
		{
			const FPhrase* Hit = nullptr;
			for (const FPhrase& Phrase : GPhrases)
				if (At+Phrase.JaLen<=Source.Len() && FCString::Strncmp(&Source[At], Phrase.Ja, Phrase.JaLen)==0) { Hit=&Phrase; break; }
			if (Hit) { Out+=Hit->Zh; At+=Hit->JaLen; }
			else { Out.AppendChar(Source[At]); ++At; }
		}
		return Out;
	};
	int32 Count=0;
