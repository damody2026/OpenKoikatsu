-- Generate common Forge iris recipe from installed DXBC, never card data.
local ok = require "ok"
local cg = require "shader_program_codegen"
local json, path = ok.json, ok.path
local root = ok.root
local bundle = ok.game_root(true) .. "/kks_decomp/plugins/KKS_Plugins/KKS_MaterialEditor/KK_Plugins.Resources.EC_Shaders.unity3d"
local shader, label = "Shader Forge/toon_eye_lod0", "Eye"

local function main()
  local tree = cg.shader_tree(bundle, shader)
  local parsed = tree.m_ParsedForm
  local raw = cg.platform_raw(tree, 4)
  local blobs = cg.scan_dxbc(raw)
  -- Raw DXBC scan index differs from the Unity blob index; assert bindings below.
  local blob = blobs[1]
  -- EC bundle Unity 5.6 uses 8-byte entries. Resolve the selected native blob,
  -- rather than trusting raw scan order or merely matching register counts.
  local selected = cg.sub_program_at(raw, 8, 8)
  assert(cg.list_eq(selected.m_Keywords, { "DIRECTIONAL" }))
  local native = cg.dxbc_in(selected.m_ProgramCode)
  assert(blob == native, "Raw scan does not match the selected native fragment blob")

  assert(cg.sha256(blob) == "7314be5e7a4b86a6b3588a05969c52173a603b1aac830b08a91eb71d4eab6172", "Installed program changed; review source first")
  local folder = root .. "/Saved/ShaderDxbc/EC_Shaders/Shader_Forge_toon_eye_lod0"
  path.mkdir(folder)
  local file = folder .. "/0000.dxbc"
  path.write_bytes(file, blob)
  local asm = cg.dumpbin(file)
  path.write_text(path.with_suffix(file, ".asm.txt"), asm)
  local pass_ = parsed.m_SubShaders[1].m_Passes[1]
  local state = pass_.m_State
  local names = cg.names(pass_.m_NameIndices)
  assert(state.culling.val == 2 and state.zWrite.val == 0 and state.rtBlend0.srcBlend.val == 5 and state.rtBlend0.destBlend.val == 10)
  local program
  for _, p in ipairs(pass_.progFragment.m_SubPrograms) do
    if p.m_GpuProgramType == 17 and p.m_BlobIndex == 8 and cg.list_eq(cg.keyword_names(names, p.m_KeywordIndices), { "DIRECTIONAL" }) then program = p break end
  end
  assert(program, "StopIteration")
  local sizes = cg.cb_sizes(asm)
  assert(cg.list_eq(sizes, { 14, 5, 1 }))
  local lines = { "// Generated by Tools/generate_runtime_forge_eye.lua; " .. shader, "static const int32 GForgeEyeForwardCBSize[]={14,5,1};", "static const FOKForgeEyeUniform GForgeEyeForwardUniforms[]={" }
  for cb, c in ipairs(program.m_ConstantBuffers) do
    for _, u in ipairs(cg.concat(c.m_VectorParams, c.m_MatrixParams)) do
      assert(u.m_Index // 16 < sizes[cb])
      lines[#lines + 1] = cg.uniform_line(names, cb - 1, u)
    end
  end
  lines[#lines + 1] = "};"
  lines[#lines + 1] = "static const FOKForgeEyeTexture GForgeEyeForwardTextures[]={"
  for _, t in ipairs(program.m_TextureParams) do
    assert(cg.uses_sampler(asm, t.m_Index, t.m_SamplerIndex))
    lines[#lines + 1] = cg.texture_line(names[t.m_NameIndex], t.m_Index, t.m_SamplerIndex, t.m_Dim)
  end
  lines[#lines + 1] = "};"
  lines[#lines + 1] = "static const FOKForgeEyeProperty GForgeEyeProperties[]={"
  for _, p in ipairs(parsed.m_PropInfo.m_Props) do lines[#lines + 1] = cg.property_line(p) end
  local output = root .. "/Plugins/KKRuntimePose/Source/KKRuntimePose/Private/SharedShaders"
  lines[#lines + 1] = "};"
  path.write_text(output .. "/ForgeEyeBindings.inl", table.concat(lines, "\n") .. "\n")
  local instructions = cg.precise_lines(blob, asm)
  -- Native expression sampling uses the original vertex eye UV plus view parallax.
  -- Runtime UV0 already owns pupil rotation; UV3 retains the native vertex varying, before MainTex EyeLook ST.
  local expression_prefix = "mad r2.xy, r3.xyxx, l(0xbd75c28f,0xbd75c28f,0x00000000,0x00000000), v1.xyxx"
  local count, at = 0, nil
  for i, l in ipairs(instructions) do if l == expression_prefix then count = count + 1; at = at or i end end
  assert(count == 1, "Review changed expression UV instruction")
  instructions[at] = expression_prefix:gsub("v1%.xyxx", "v7.xyxx")
  local body = "\n" .. cg.translate(instructions) .. "\n"
  local sha = cg.sha256(blob)
  local code = { "// Installed DXBC with explicit pre-rotation expression input; SHA256 " .. sha, "static const TCHAR* GForgeEyeForwardProgram=" }
  cg.text_chunks(body, code)
  code[#code + 1] = ";"
  path.write_text(output .. "/ForgeEyeProgram.inl", table.concat(code, "\n") .. "\n")
  print(json.encode(json.object({ { "shader", shader }, { "dxbc_sha256", sha }, { "raw_index", 0 }, { "native_blob", 8 }, { "keywords", { "DIRECTIONAL" } },
    { "cull_back", true }, { "native_depth_write", false }, { "native_stencil_ref", state.stencilRef.val }, { "native_stencil_pass", state.stencilOp.pass.val },
    { "runtime_stencil_equivalence_verified", false }, { "per_card_input", false }, { "expression_input_remap", true },
    { "original_expression_parallax_preserved", true } }), { indent = 2 }))
end

ok.main(main)
