-- Generate common Forge nose recipe from installed DXBC, never card data.
local ok = require "ok"
local cg = require "shader_program_codegen"
local json, path = ok.json, ok.path
local root = ok.root
local bundle = ok.game_root(true) .. "/kks_decomp/plugins/KKS_Plugins/KKS_MaterialEditor/KK_Plugins.Resources.EC_Shaders.unity3d"
local shader, label = "Shader Forge/toon_nose_lod0", "Nose"

local function main()
  local tree = cg.shader_tree(bundle, shader)
  local parsed = tree.m_ParsedForm
  local raw = cg.platform_raw(tree, 4)
  local blobs = cg.scan_dxbc(raw)
  -- Raw DXBC scan index differs from the Unity blob index; assert bindings below.
  -- EC bundle Unity 5.6 uses 8-byte entries. Resolve the selected native blob,
  -- rather than trusting raw scan order or merely matching register counts.
  local selected = cg.sub_program_at(raw, 8, 8)
  assert(cg.list_eq(selected.m_Keywords, { "DIRECTIONAL" }))
  local blob = cg.dxbc_in(selected.m_ProgramCode)
  local raw_index
  for i, b in ipairs(blobs) do if b == blob then raw_index = i - 1 break end end
  assert(raw_index ~= nil)

  assert(cg.sha256(blob) == "875ff86184832554b4664cdca4196b992f56af88c2615284f90bcc55544b667c", "Installed nose changed; review source")
  local folder = root .. "/Saved/ShaderDxbc/EC_Shaders/Shader_Forge_toon_nose_lod0"
  path.mkdir(folder)
  local file = folder .. "/selected8.dxbc"
  path.write_bytes(file, blob)
  local asm = cg.dumpbin(file)
  path.write_text(path.with_suffix(file, ".asm.txt"), asm)
  -- Validate the native vertex stage independently: the fragment must receive
  -- unchanged UV0, with _MainTex_ST applied exactly once in the pixel program.
  local vertex = cg.sub_program_at(raw, 0, 8)
  assert(cg.list_eq(vertex.m_Keywords, { "DIRECTIONAL" }))
  local vertex_blob = cg.dxbc_in(vertex.m_ProgramCode)
  local vertex_path = folder .. "/vertex0.dxbc"
  path.write_bytes(vertex_path, vertex_blob)
  local vertex_asm = cg.dumpbin(vertex_path)
  path.write_text(path.with_suffix(vertex_path, ".asm.txt"), vertex_asm)
  local vertex_instructions = cg.precise_lines(vertex_blob, vertex_asm)
  local uv = {}
  for _, l in ipairs(vertex_instructions) do
    if l:sub(1, 4) ~= "dcl_" and l:find("%f[%w_]o1%.") then uv[#uv + 1] = l end
  end
  assert(cg.list_eq(uv, { "mov o1.xy, v1.xyxx" }), "Review changed native UV0 varying")

  local pass_ = parsed.m_SubShaders[1].m_Passes[1]
  local state = pass_.m_State
  local names = cg.names(pass_.m_NameIndices)
  assert(state.culling.val == 2 and state.zWrite.val == 0 and state.rtBlend0.srcBlend.val == 5 and state.rtBlend0.destBlend.val == 10)
  local program
  for _, p in ipairs(pass_.progFragment.m_SubPrograms) do
    if p.m_GpuProgramType == 17 and p.m_BlobIndex == 8 and cg.list_eq(cg.keyword_names(names, p.m_KeywordIndices), { "DIRECTIONAL" }) then program = p break end
  end
  assert(program, "StopIteration")
  local sizes = cg.cb_sizes(asm)
  assert(cg.list_eq(sizes, { 4 }))
  local lines = { "// Generated by Tools/generate_runtime_forge_nose.lua; " .. shader, "static const int32 GForgeNoseForwardCBSize[]={4};", "static const FOKForgeNoseUniform GForgeNoseForwardUniforms[]={" }
  for cb, c in ipairs(program.m_ConstantBuffers) do
    for _, u in ipairs(cg.concat(c.m_VectorParams, c.m_MatrixParams)) do
      assert(u.m_Index // 16 < sizes[cb])
      lines[#lines + 1] = cg.uniform_line(names, cb - 1, u)
    end
  end
  lines[#lines + 1] = "};"
  lines[#lines + 1] = "static const FOKForgeNoseTexture GForgeNoseForwardTextures[]={"
  for _, t in ipairs(program.m_TextureParams) do
    assert(cg.uses_sampler(asm, t.m_Index, t.m_SamplerIndex))
    lines[#lines + 1] = cg.texture_line(names[t.m_NameIndex], t.m_Index, t.m_SamplerIndex, t.m_Dim)
  end
  lines[#lines + 1] = "};"
  lines[#lines + 1] = "static const FOKForgeNoseProperty GForgeNoseProperties[]={"
  for _, p in ipairs(parsed.m_PropInfo.m_Props) do lines[#lines + 1] = cg.property_line(p) end
  local output = root .. "/Plugins/KKRuntimePose/Source/KKRuntimePose/Private/SharedShaders"
  lines[#lines + 1] = "};"
  path.write_text(output .. "/ForgeNoseBindings.inl", table.concat(lines, "\n") .. "\n")
  local body = "\n" .. cg.translate(cg.precise_lines(blob, asm)) .. "\n"
  local sha = cg.sha256(blob)
  local code = { "// Exact installed DXBC; SHA256 " .. sha, "static const TCHAR* GForgeNoseForwardProgram=" }
  cg.text_chunks(body, code)
  code[#code + 1] = ";"
  path.write_text(output .. "/ForgeNoseProgram.inl", table.concat(code, "\n") .. "\n")
  print(json.encode(json.object({ { "shader", shader }, { "dxbc_sha256", sha }, { "raw_index", raw_index }, { "native_blob", 8 }, { "keywords", { "DIRECTIONAL" } },
    { "cull_back", true }, { "native_depth_write", false }, { "native_stencil_ref", state.stencilRef.val }, { "native_stencil_pass", state.stencilOp.pass.val },
    { "runtime_stencil_equivalence_verified", false }, { "per_card_input", false }, { "vertex_uv0_identity_verified", true },
    { "vertex_dxbc_sha256", cg.sha256(vertex_blob) } }), { indent = 2 }))
end

ok.main(main)
