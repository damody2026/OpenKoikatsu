-- Generate common Forge hair pixel recipes from verified installed DXBC; no cards.
local ok = require "ok"
local cg = require "shader_program_codegen"
local json, path = ok.json, ok.path
local root = ok.root
local bundle = ok.game_root(true) .. "/kks_decomp/plugins/KKS_Plugins/KKS_MaterialEditor/KK_Plugins.Resources.EC_Shaders.unity3d"
local output = root .. "/Plugins/KKRuntimePose/Source/KKRuntimePose/Private/SharedShaders"

local function main()
  local receipts = json.array({})
  for _, spec in ipairs({ { "Shader Forge/main_hair", "Hair", 0 }, { "Shader Forge/main_hair_front", "HairFront", 5 } }) do
    local shader, label, raw_index = spec[1], spec[2], spec[3]
    local tree = cg.shader_tree(bundle, shader)
    local parsed = tree.m_ParsedForm
    local raw = cg.platform_raw(tree, 4)
    local installed = cg.scan_dxbc(raw)
    local folder = root .. "/Saved/ShaderDxbc/EC_Shaders/" .. shader:gsub(" ", "_"):gsub("/", "_")
    local blob = path.read_bytes(string.format("%s/%04d.dxbc", folder, raw_index))
    local asm = path.read_text(string.format("%s/%04d.asm.txt", folder, raw_index))
    assert(blob == installed[raw_index + 1], "DXBC cache differs from installed source")
    assert(asm:find("dcl_input_ps_sgv v6.x, isfrontface", 1, true) or asm:find("v6.x", 1, true))
    assert(not asm:find("v7.x", 1, true) and asm:find("v1.zw", 1, true))
    local pass_ = parsed.m_SubShaders[1].m_Passes[2]
    local names = cg.names(pass_.m_NameIndices)
    local program
    for _, p in ipairs(pass_.progFragment.m_SubPrograms) do
      if (p.m_GpuProgramType == 15 or p.m_GpuProgramType == 17) and cg.list_eq(cg.keyword_names(names, cg.get(p, "m_KeywordIndices", {})), { "DIRECTIONAL" }) then program = p break end
    end
    assert(program, "StopIteration")
    local sizes = cg.cb_sizes(asm)
    assert(cg.list_eq(sizes, { 19, 5, 1 }))
    local lines = { "// Generated by Tools/generate_runtime_forge_hair.lua; " .. shader .. ".", "static const int32 GForge" .. label .. "ForwardCBSize[]={" .. table.concat(sizes, ",") .. "};",
      "static const FOKForge" .. label .. "Uniform GForge" .. label .. "ForwardUniforms[]={" }
    for cb, c in ipairs(program.m_ConstantBuffers) do
      for _, u in ipairs(cg.concat(c.m_VectorParams, c.m_MatrixParams)) do
        assert(u.m_Index // 16 < sizes[cb])
        lines[#lines + 1] = cg.uniform_line(names, cb - 1, u)
      end
    end
    lines[#lines + 1] = "};"
    lines[#lines + 1] = "static const FOKForge" .. label .. "Texture GForge" .. label .. "ForwardTextures[]={"
    for _, t in ipairs(program.m_TextureParams) do
      assert(cg.uses_sampler(asm, t.m_Index, t.m_SamplerIndex))
      lines[#lines + 1] = cg.texture_line(names[t.m_NameIndex], t.m_Index, t.m_SamplerIndex, t.m_Dim)
    end
    lines[#lines + 1] = "};"
    lines[#lines + 1] = "static const FOKForge" .. label .. "Property GForge" .. label .. "Properties[]={"
    for _, p in ipairs(parsed.m_PropInfo.m_Props) do lines[#lines + 1] = cg.property_line(p) end
    lines[#lines + 1] = "};"
    path.write_text(output .. "/Forge" .. label .. "Bindings.inl", table.concat(lines, "\n") .. "\n")
    local body = "\n" .. cg.translate(cg.precise_lines(blob, asm)) .. "\n"
    local sha = cg.sha256(blob)
    local code = { "// Exact installed DXBC; SHA256 " .. sha, "static const TCHAR* GForge" .. label .. "ForwardProgram=" }
    cg.text_chunks(body, code)
    code[#code + 1] = ";"
    path.write_text(output .. "/Forge" .. label .. "Program.inl", table.concat(code, "\n") .. "\n")
    receipts[#receipts + 1] = json.object({ { "shader", shader }, { "dxbc_sha256", sha }, { "raw_index", raw_index }, { "native_blob", program.m_BlobIndex },
      { "keywords", { "DIRECTIONAL" } }, { "secondary_uv", true }, { "per_card_input", false } })
  end
  print(json.encode(receipts, { indent = 2 }))
end

ok.main(main)
