-- Generate common Koikano iris recipe from installed DXBC, never card data.
local ok = require "ok"
local cg = require "shader_program_codegen"
local json, path = ok.json, ok.path
local root = ok.root
local bundle = ok.game_root(true) .. "/kks_decomp/plugins/KKS_Plugins/KKS_MaterialEditor/KK_Plugins.Resources.KKS_Shaders.unity3d"
local shader, label = "Koikano/main_eye", "KoikanoEye"

local function main()
  local tree = cg.shader_tree(bundle, shader)
  local parsed = tree.m_ParsedForm
  local raw = cg.platform_raw(tree, 4)
  local blobs = cg.scan_dxbc(raw)
  -- Raw DXBC scan index differs from the Unity blob index; assert bindings below.
  -- KKS bundle Unity 2019.4 uses 12-byte entries. Resolve the selected native blob,
  -- rather than trusting raw scan order or merely matching register counts.
  local selected = cg.sub_program_at(raw, 8, 12)
  assert(cg.list_eq(selected.m_Keywords, { "DIRECTIONAL" }))
  local blob = cg.dxbc_in(selected.m_ProgramCode)
  local raw_index
  for i, b in ipairs(blobs) do if b == blob then raw_index = i - 1 break end end
  assert(raw_index ~= nil)

  assert(cg.sha256(blob) == "76475799721ba954cb4b3074cfd737c807fad41939d8befb422f4ee7350145d0", "Installed shader changed; review source")
  local folder = root .. "/Saved/ShaderDxbcKKS/KK_Plugins.Resources.KKS_Shaders/Koikano_main_eye"
  path.mkdir(folder)
  local file = folder .. "/selected8.dxbc"
  path.write_bytes(file, blob)
  local asm = cg.dumpbin(file)
  path.write_text(path.with_suffix(file, ".asm.txt"), asm)
  local pass_ = parsed.m_SubShaders[1].m_Passes[1]
  local state = pass_.m_State
  local names = cg.names(pass_.m_NameIndices)
  assert(state.culling.val == 2 and state.zWrite.val == 0 and state.rtBlend0.srcBlend.val == 5 and state.rtBlend0.destBlend.val == 10)
  local program
  for _, p in ipairs(pass_.progFragment.m_SubPrograms) do
    local keys = p.m_KeywordIndices or cg.concat(cg.get(p, "m_GlobalKeywordIndices", {}), cg.get(p, "m_LocalKeywordIndices", {}))
    if p.m_GpuProgramType == 17 and p.m_BlobIndex == 8 and cg.list_eq(cg.keyword_names(names, keys), { "DIRECTIONAL" }) then program = p break end
  end
  assert(program, "StopIteration")
  local sizes = cg.cb_sizes(asm)
  assert(cg.list_eq(sizes, { 18, 5, 47, 8, 7 }))
  local lines = { "// Generated by Tools/generate_runtime_koikano_eye.lua; " .. shader, "static const int32 GKoikanoEyeForwardCBSize[]={" .. table.concat(sizes, ",") .. "};", "static const FOKKoikanoEyeUniform GKoikanoEyeForwardUniforms[]={" }
  for cb, c in ipairs(program.m_ConstantBuffers) do
    for _, u in ipairs(cg.concat(c.m_VectorParams, c.m_MatrixParams)) do
      assert(u.m_Index // 16 < sizes[cb])
      lines[#lines + 1] = cg.uniform_line(names, cb - 1, u)
    end
  end
  lines[#lines + 1] = "};"
  lines[#lines + 1] = "static const FOKKoikanoEyeTexture GKoikanoEyeForwardTextures[]={"
  for _, t in ipairs(program.m_TextureParams) do
    local used_samplers = cg.samplers_of(asm, t.m_Index)
    assert(#used_samplers == 1)
    local sampler = used_samplers[1]
    assert(t.m_SamplerIndex == -1 or t.m_SamplerIndex == sampler)
    lines[#lines + 1] = cg.texture_line(names[t.m_NameIndex], t.m_Index, sampler, t.m_Dim)
  end
  lines[#lines + 1] = "};"
  lines[#lines + 1] = "static const FOKKoikanoEyeProperty GKoikanoEyeProperties[]={"
  for _, p in ipairs(parsed.m_PropInfo.m_Props) do lines[#lines + 1] = cg.property_line(p) end
  local output = root .. "/Plugins/KKRuntimePose/Source/KKRuntimePose/Private/SharedShaders"
  lines[#lines + 1] = "};"
  path.write_text(output .. "/KoikanoEyeBindings.inl", table.concat(lines, "\n") .. "\n")
  local instructions = cg.precise_lines(blob, asm)
  local expression_index, count = nil, 0
  for i, l in ipairs(instructions) do
    if l:sub(1, #"mad r2.zw, r2.zzzw,") == "mad r2.zw, r2.zzzw," then count = count + 1; expression_index = expression_index or i end
  end
  assert(expression_index, "StopIteration")
  assert(count == 1)
  -- Native vertex input (UV0 * _texcoord_ST) is retained on runtime UV3. Restore
  -- that coordinate immediately before the original expression scale/bias.
  table.insert(instructions, expression_index, "mov r2.zw, v7.xxxy")
  local body = "\n" .. cg.translate(instructions) .. "\n"
  local sha = cg.sha256(blob)
  local code = { "// Installed DXBC with explicit unrotated expression input; SHA256 " .. sha, "static const TCHAR* GKoikanoEyeForwardProgram=" }
  cg.text_chunks(body, code)
  code[#code + 1] = ";"
  path.write_text(output .. "/KoikanoEyeProgram.inl", table.concat(code, "\n") .. "\n")
  print(json.encode(json.object({ { "shader", shader }, { "dxbc_sha256", sha }, { "raw_index", raw_index }, { "native_blob", 8 }, { "keywords", { "DIRECTIONAL" } },
    { "cull_back", true }, { "native_depth_write", false }, { "native_stencil_ref", state.stencilRef.val }, { "native_stencil_pass", state.stencilOp.pass.val },
    { "runtime_stencil_equivalence_verified", false }, { "per_card_input", false }, { "expression_input_remap", true },
    { "shared_cube_sampler", true } }), { indent = 2 }))
end

ok.main(main)
